"""Union the approved LAB logo shapes and emit matching SVG / Flutter paths.

Uses the same fonttools / skia-pathops dependencies as generate_studio_icons.py.
The editable source retains separate pixel blocks; the shipped outlines are one fill.
"""

from pathlib import Path
import xml.etree.ElementTree as ET

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.svgLib.path import SVGPath
import pathops


def main():
    root = Path(__file__).resolve().parents[2]
    source = ET.parse(Path(__file__).with_name('wof_nai_lab_source.svg')).getroot()
    outline = pathops.Path()
    for element in source.iter('{http://www.w3.org/2000/svg}path'):
        shape = pathops.Path()
        SVGPath.fromstring(ET.tostring(element)).draw(shape.getPen())
        if element.get('fill-rule') == 'evenodd':
            shape.fillType = pathops.FillType.EVEN_ODD
        outline = pathops.op(outline, shape, pathops.PathOp.UNION)
    pen = SVGPathPen(None)
    outline.draw(pen)
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{source.attrib["viewBox"]}">\n'
        '  <title>W.O.F NAI LAB</title>\n'
        '  <!-- Generated by tool/branding/generate_lab_logo.py. One unioned fill avoids internal seams. -->\n'
        f'  <path fill="#005DFF" d="{pen.getCommands()}"/>\n'
        '</svg>\n'
    )
    (root / 'assets/images/wof_nai_lab.svg').write_text(svg, encoding='utf-8')

    commands = RecordingPen()
    outline.draw(commands)
    dart = [
        '// Generated by tool/branding/generate_lab_logo.py. Do not edit by hand.',
        "import 'dart:ui' as ui;",
        '',
        'final ui.Path labLogoPath = ui.Path()',
    ]
    for operation, points in commands.value:
        if operation in ('moveTo', 'lineTo'):
            x, y = points[0]
            dart.append(f'  ..{operation}({x}, {y})')
        elif operation == 'qCurveTo':
            assert len(points) >= 2 and points[-1] is not None, points
            for control, next_control in zip(points[:-2], points[1:-1]):
                x1, y1 = control
                x2 = (x1 + next_control[0]) / 2
                y2 = (y1 + next_control[1]) / 2
                dart.append(f'  ..quadraticBezierTo({x1}, {y1}, {x2}, {y2})')
            (x1, y1), (x2, y2) = points[-2:]
            dart.append(f'  ..quadraticBezierTo({x1}, {y1}, {x2}, {y2})')
        elif operation == 'closePath':
            dart.append('  ..close()')
        else:
            raise ValueError(f'Unsupported LAB outline operation: {operation}')
    dart[-1] += ';'
    dart.append('')
    (root / 'lib/presentation/screens/style_explore/widgets/lab_logo_path.dart').write_text(
        '\n'.join(dart), encoding='utf-8'
    )


if __name__ == '__main__':
    main()
