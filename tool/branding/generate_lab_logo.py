"""Union the approved LAB logo shapes to remove internal antialias seams.

Uses the same fonttools / skia-pathops dependencies as generate_studio_icons.py.
The editable source retains separate pixel blocks; the shipped asset is one fill.
"""

from pathlib import Path
import xml.etree.ElementTree as ET

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.svgLib.path import parse_path
import pathops


def main():
    root = Path(__file__).resolve().parents[2]
    source = ET.parse(Path(__file__).with_name('wof_nai_lab_source.svg')).getroot()
    outline = pathops.Path()
    for element in source.iter('{http://www.w3.org/2000/svg}path'):
        shape = pathops.Path()
        parse_path(element.attrib['d'], shape.getPen())
        if element.get('fill-rule') == 'evenodd':
            shape.fillType = pathops.FillType.EVEN_ODD
        outline = pathops.op(outline, shape, pathops.PathOp.UNION)
    pen = SVGPathPen(None)
    outline.draw(pen)
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{source.attrib["viewBox"]}">\n'
        '  <title>W.O.F NAI LAB</title>\n'
        '  <!-- Generated by tool/branding/generate_lab_logo.py. One unioned fill avoids internal seams. -->\n'
        f'  <path fill="#005DFF" d="{pen.getCommands()}"/>\n'
        '</svg>\n'
    )
    (root / 'assets/images/wof_nai_lab.svg').write_text(svg, encoding='utf-8')


if __name__ == '__main__':
    main()
