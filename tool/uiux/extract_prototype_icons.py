"""Copy the selected HTML prototype paths into Dart without redrawing them."""
import argparse
from pathlib import Path
import re


def paths(source):
    html = Path(source).read_text(encoding="utf-8")
    match = re.search(r"const P\s*=\s*\{(.*?)\};", html, re.S)
    if not match:
        raise ValueError(f"No prototype path table in {source}")
    entries = dict(re.findall(r"([A-Za-z][A-Za-z0-9_]*):'([^']*)'", match[1]))
    entries.update(re.findall(r"P\.([A-Za-z][A-Za-z0-9_]*)\s*=\s*'([^']*)'", html))
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--blocks", required=True)
    parser.add_argument("--generation", required=True)
    parser.add_argument("--viewer", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    lines = [
        "// Generated by tool/uiux/extract_prototype_icons.py. Do not edit.",
        "// Sources: .devin/mockups/{blocks,generation}/mock.html, const P.",
        "// Translation tr: .devin/mockups/viewer/mock.html, const P.",
        "",
    ]
    for name, source in (("blocks", args.blocks), ("generation", args.generation)):
        entries = paths(source)
        if name == "blocks":
            entries["tr"] = paths(args.viewer)["tr"]
        lines.append(f"const {name}PrototypeIconPaths = <String, String>{{")
        lines.extend(f"  '{key}': '{value}'," for key, value in entries.items())
        lines.extend(["};", ""])
    Path(args.output).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
