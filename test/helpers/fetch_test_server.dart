Future<HttpServer> bindFetchTestServer() async {
  for (var attempt = 0; attempt < 64; attempt++) {
    final server = await HttpServer.bind(InternetAddress.loopbackIPv4, 0);
    if (!fetchBlockedPorts.contains(server.port)) return server;
    await server.close(force: true);
  }
  throw StateError('No Node-fetch-compatible loopback port was allocated');
}
